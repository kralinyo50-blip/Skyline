export function personaOf(name: string): Persona {
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return BOT_PERSONAS[h % BOT_PERSONAS.length];
}

export function personaLine(name: string): string {
  const p = personaOf(name);
  return Math.random() < 0.72 ? p.lines[Math.floor(Math.random() * p.lines.length)] : pickLine(CHAT_LINES);
}

function pickLine(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

