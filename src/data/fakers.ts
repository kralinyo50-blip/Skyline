export interface BotReply {
  text: string;
  countered: boolean;
}

/** Bir bot mesajına en uygun doğal cevabı seç (anahtar kelime eşleşmezse genel) */
export function replyToMessage(text: string): BotReply {
  const t = text.toLowerCase();
  for (const r of CHAT_REACTIONS) {
    if (r.match.some((m) => t.includes(m))) {
      const countered = r.counters.length > 0 && Math.random() < 0.3;
      const pool = countered ? r.counters : r.replies;
      return { text: pickLine(pool), countered };
    }
  }
  return { text: pickLine(CHAT_REPLIES), countered: false };
}

