export function timeAwareLine(): string {
  const d = new Date();
  const h = d.getHours();
  const pool = h >= 5 && h < 11 ? TIME_LINES.morning : h >= 11 && h < 18 ? TIME_LINES.afternoon : h >= 18 && h < 23 ? TIME_LINES.evening : TIME_LINES.night;
  const arr = d.getDay() === 6 || d.getDay() === 0 ? [...pool, ...TIME_LINES.weekend] : pool;
  return pickLine(arr);
}

